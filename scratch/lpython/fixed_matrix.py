def apply_op(op: i32, a: i64, b: i64, width: i32, signed: i32) -> i64:
    if op == 0:
        return add(a, b, width)
    if op == 1:
        return sub(a, b, width)
    if op == 2:
        return mul(a, b, width)
    if op == 3:
        return div(a, b, width, signed)
    if op == 4:
        return mod(a, b, width, signed)
    if op == 5:
        return land(a, b, width)
    if op == 6:
        return lor(a, b, width)
    if op == 7:
        return xor(a, b, width)
    if op == 8:
        return shift_left(a, b, width)
    if op == 9:
        return shift_right(a, b, width, signed)
    if op == 10:
        return i64(dec_lt(a, b, width, signed))
    if op == 11:
        return i64(dec_le(a, b, width, signed))
    if op == 12:
        return complement(a, width)
    if op == 13:
        return neg(a, width)
    if op == 14:
        return abs_(a, width)
    if op == 15:
        return log2(a, width)
    return i64(0)


